export function buildCountryMarketPrompt(country: string, snapshot: string) {
  const instructions = COUNTRY_RESEARCH_INSTRUCTIONS.split('{COUNTRY}').join(country);
  return composeVibeResearchPrompt(instructions, snapshot, `${country}市场相关终端快照`);
}

export function buildEquityResearchPrompt(equity: string, snapshot: string) {
  const instructions = EQUITY_RESEARCH_INSTRUCTIONS.split('{EQUITY}').join(equity);
  return composeVibeResearchPrompt(instructions, snapshot, `${equity}研究相关终端快照`);
}
