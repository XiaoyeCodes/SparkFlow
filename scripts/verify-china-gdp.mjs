import assert from 'node:assert/strict';
import {createChinaGdpService, gdpBulletins, parseGdpBulletin, GDP_LIST_URL} from '../server/chinaGdp.ts';
const bulletin = (year, value = 1401879) => `<h1>中华人民共和国${year}年国民经济和社会发展统计公报</h1>初步核算，全年国内生产总值[2]${value}亿元，按不变价格计算，比上年增长5.0%。人均国内生产总值99665元。`;
const parsed = parseGdpBulletin(bulletin(2025),2025,'https://www.stats.gov.cn/test');
assert.equal(parsed.value,140.1879);
assert.equal(parsed.growth,5);
assert.equal(parseGdpBulletin(bulletin(2025).replace('增长','下降'),2025,'https://www.stats.gov.cn/test').growth,-5);
assert.throws(()=>parseGdpBulletin(bulletin(2025),2024,''));
assert.throws(()=>parseGdpBulletin('2025年国民经济和社会发展统计公报，人均国内生产总值99665元',2025,''));
const list = [2025,2024,2023,2022,2021].map(year=>`<a href="./${year}.html">${year}年</a>`).join('');
assert.equal(gdpBulletins(list+list+'<a href="https://example.com/">2026年</a>').length,5);
let calls = 0;
let offline = false;
let now = Date.parse('2026-09-13T00:00:00Z');
const service = createChinaGdpService(async url=>{
  calls++;
  if(offline)throw new Error('offline');
  return url === GDP_LIST_URL ? list : bulletin(Number(url.match(/(20\d{2})\.html/)[1]));
},()=>now);
const [a,b] = await Promise.all([service(),service()]);
assert.deepEqual(a,b);
assert.equal(a.status,'current');
assert.equal(calls,6);
await service();assert.equal(calls,6);
offline=true;now+=3600_000;
assert.equal((await service()).years.length,0);
offline=false;now+=60_000;
assert.equal((await service()).years.length,5);
now=Date.parse('2027-03-01T00:00:00Z');
assert.equal((await service()).status,'unavailable','old annual bulletin must not be labelled current indefinitely');
console.log('China GDP: official periods, units, growth parsing, cache concurrency, outage/recovery and annual expiry passed.');
