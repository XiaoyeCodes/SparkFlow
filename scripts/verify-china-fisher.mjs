import assert from 'node:assert/strict';
import { createChinaFisherService, evaluateFisher, parseCpiCalendar, readFisherObservation, readDepositObservation, CPI_CALENDAR_URL, DEPOSIT_LIST_URL } from '../server/chinaFisher.ts';

const at = value => Date.parse(value + '+08:00');
const calendarHtml = (year = 2026) => `<h1>${year}年国家统计局主要统计信息发布日程表</h1><table><tr><td>5</td><td>居民消费价格指数月度报告</td>${Array.from({length:12}, (_, i) => `<td>${i === 9 ? 14 : 9}/一</td>`).join('')}</tr><tr>${'<td>9:30</td>'.repeat(12)}</tr></table>`;
const calendar = parseCpiCalendar(calendarHtml());
const nominal = {value:3, period:'2026-08',publishedAt:'2026-08-20',source:'中国人民银行',sourceUrl:'https://www.pbc.gov.cn/test'};
const inflation = {value:0.8,period:'2026-08',publishedAt:'2026-09-09',source:'国家统计局',sourceUrl:'https://www.stats.gov.cn/test'};
const evaluate = (date, n = nominal, i = inflation, c = calendar) => evaluateFisher(n, i, c, at(date));
assert.equal(evaluate('2026-09-13T11:00:00').realRate, 2.2);
assert.equal(evaluate('2026-09-13T11:00:00', nominal, {...inflation,value:-0.8}).realRate, 3.8);
assert.equal(evaluate('2026-09-13T11:00:00', nominal, {...inflation,value:4}).realRate, -1);
assert.equal(evaluate('2026-09-13T11:00:00', nominal, {...inflation,value:0}).realRate, 3);
const oldCpi = {...inflation,period:'2026-07',publishedAt:'2026-08-09'};
assert.equal(evaluate('2026-09-09T09:29:59', nominal, oldCpi).status, 'current');
assert.equal(evaluate('2026-09-09T09:30:00', nominal, oldCpi).realRate, null);
assert.equal(evaluate('2026-09-20T08:59:59').status, 'current');
assert.equal(evaluate('2026-09-20T09:00:00').realRate, null, 'holiday deferral must not relabel last month as new');
assert.equal(evaluate('2026-09-21T09:00:00', {...nominal,period:'2026-09',publishedAt:'2026-09-21'}).status, 'current');
assert.equal(evaluate('2026-09-13T11:00:00', {...nominal,publishedAt:'2026-09-14'}).realRate, null);
assert.equal(evaluate('2026-09-13T11:00:00', nominal, {...inflation,period:'2026-09'}).realRate, null);
assert.equal(calendar[9].at, at('2026-10-14T09:30:00'), 'must respect official October exception');
assert.equal(evaluate('2027-01-05T11:00:00').realRate, null, 'old calendar must not remain valid across years');
assert.equal(evaluate('2027-01-05T11:00:00', {...nominal,period:'2026-12',publishedAt:'2026-12-21'}, {...inflation,period:'2026-11',publishedAt:'2026-12-09'}, parseCpiCalendar(calendarHtml(2027))).status, 'current');
assert.throws(() => parseCpiCalendar('<html>服务繁忙</html>'));

let reads = 0;
let fail = false;
let time = at('2026-09-13T11:00:00');
let cpiBody = '全国居民消费价格同比上涨0.8%。全国居民消费价格环比上涨0.1%。';
const read = async url => {
  reads++;
  if (fail) throw new Error('offline');
  if (url === CPI_CALENDAR_URL) return calendarHtml();
  if (url.endsWith('/125440/index.html')) return '<a href="./release">2026年8月20日全国银行间同业拆借中心受权公布贷款市场报价利率（LPR）公告</a>';
  if (url.endsWith('/sj/zxfb/')) return '<li><a href="./release">2026年8月份居民消费价格同比上涨0.8%</a><span>2026-09-09</span></li>';
  if (url.includes('pbc.gov.cn')) return '2026年8月20日贷款市场报价利率为：1年期LPR为3.0%，5年期以上LPR为3.5%。';
  return `<meta name="PubDate" content="2026-09-09">${cpiBody}`;
};
assert.equal((await readFisherObservation('inflation', read)).value, 0.8);
cpiBody = '全国居民消费价格同比持平。全国居民消费价格环比上涨0.1%。';
assert.equal((await readFisherObservation('inflation', read)).value, 0);
cpiBody = '全国居民消费价格同比下降0.8%。';
assert.equal((await readFisherObservation('inflation', read)).value, -0.8);
cpiBody = '全国居民消费价格环比上涨0.8%。';
await assert.rejects(readFisherObservation('inflation', read), /同比/);
cpiBody = '全国居民消费价格同比上涨0.8%。';
reads = 0;
const service = createChinaFisherService(read, () => time);
const [a,b] = await Promise.all([service(), service()]);
assert.equal(a.realRate, 2.2);
assert.deepEqual(a,b);
assert.equal(reads,5, 'simultaneous requests must share one upstream fetch');
await service();
assert.equal(reads,5);
time += 5 * 60_000;
fail = true;
const failed = await service();
assert.equal(failed.realRate, null);
assert.equal(failed.status, 'unavailable');
const readsAfterFailure = reads;
await service();
assert.equal(reads,readsAfterFailure, 'source failure must back off');
time += 60_000;
fail = false;
assert.equal((await service()).realRate,2.2, 'must recover automatically');
console.log('China Fisher: formula, official parsing, release boundaries, year rollover, freshness, deduplication and recovery passed.');

let depositFails = false;
let depositDate = '2025-05-20';
let depositValue = '0.95';
const readWithDeposit = async url => {
  if (!url.includes('bankofchina.com')) return read(url);
  if (depositFails) throw new Error('bank offline');
  if (url === DEPOSIT_LIST_URL) return `<a href="./latest.html">人民币存款利率表${depositDate}</a><a href="./old.html">人民币存款利率表2024-10-18</a>`;
  return `<h1>人民币存款利率表${depositDate}</h1><table><tr><td>1.整存整取</td></tr><tr><td>一年</td><td>${depositValue}&nbsp;</td></tr><tr><td>2.零存整取</td></tr><tr><td>一年</td><td>0.65</td></tr></table>`;
};
assert.equal((await readDepositObservation(readWithDeposit)).value,0.95, 'select lump-sum deposit, not the other one-year product');
const both = createChinaFisherService(readWithDeposit, () => time);
assert.equal((await both('deposit')).realRate,0.15);
assert.equal((await both('loan')).realRate,2.2,'modes must not share nominal-rate cache');
time += 5 * 60_000;
depositDate = '2026-09-13';
depositValue = '0.90';
assert.equal((await both('deposit')).realRate,0.1,'discover replacement table without a code change');
time += 5 * 60_000;
depositDate = '2025-05-20';
assert.equal((await both('deposit')).status,'unavailable','reject regressed official table');
depositFails = true;
time += 60_000;
assert.equal((await both('deposit')).realRate,null);
assert.equal((await both('loan')).realRate,2.2,'bank outage must not disable LPR');
const deposit = {...nominal,value:0.95,period:'2025-05',publishedAt:'2025-05-20'};
assert.equal(evaluateFisher(deposit,inflation,calendar,at('2026-09-20T09:00:00'),'deposit').realRate,0.15,'an unchanged deposit table has no monthly LPR deadline');
assert.equal(evaluateFisher(deposit,oldCpi,calendar,at('2026-09-09T09:30:00'),'deposit').realRate,null,'deposit still requires latest CPI');
console.log('Deposit mode: product parsing, latest table discovery, independent caches, regression protection and CPI expiry passed.');
